import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen } from '@testing-library/react'
import Accounts from './Accounts'

const accounts = [{ id: 'unassigned', name: 'Unassigned', type: 'other', openingBalance: 0 }, { id: 'cash', name: 'Cash', type: 'cash', openingBalance: 100 }]
const base = { accounts, transfers: [], transactions: [], onAccountsChange: vi.fn(), onTransfersChange: vi.fn() }
beforeEach(() => { HTMLDialogElement.prototype.showModal = function () { this.setAttribute('open', '') } })
afterEach(() => { cleanup(); vi.clearAllMocks() })
describe('account modal workflows', () => {
  it('shows the insertion line and inserts at the indicated position', () => {
    const cards = [accounts[1], { id: 'bank', name: 'Bank', type: 'bank', openingBalance: 100 }, { id: 'wallet', name: 'Wallet', type: 'cash', openingBalance: 50 }]
    const { container } = render(<Accounts {...base} accounts={cards} />)
    const [cash, bank] = container.querySelectorAll('.account-card')
    bank.getBoundingClientRect = () => ({ left: 100, width: 200 })
    const dataTransfer = { setData: vi.fn() }
    fireEvent.dragStart(cash, { dataTransfer })
    const dragOver = new Event('dragover', { bubbles: true, cancelable: true })
    Object.defineProperties(dragOver, { clientX: { value: 280 }, dataTransfer: { value: dataTransfer } })
    fireEvent(bank, dragOver)
    expect(bank.parentElement.querySelector('.account-drop-after')).not.toBeNull()
    fireEvent.drop(bank, { dataTransfer })
    expect(base.onAccountsChange.mock.calls[0][0].map(a => a.id)).toEqual(['bank', 'cash', 'wallet'])
    expect(container.querySelector('.account-drop-line')).toBeNull()
    fireEvent.dragEnd(cash)
  })
  it('zeros the actual unassigned balance by offsetting activity only after saving', () => {
    render(<Accounts {...base} transactions={[{ id: 'legacy', type: 'income', amount: 2500, description: 'Earlier salary', date: '2026-11-01' }]} />)
    fireEvent.click(screen.getByRole('button', { name: 'Edit Unassigned account' }))
    fireEvent.click(screen.getByRole('button', { name: 'Set balance to ₱0' }))
    expect(base.onAccountsChange).not.toHaveBeenCalled()
    expect(screen.getByLabelText('Opening balance (₱)')).toHaveValue(-2500)
    expect(screen.getByText('Balance after saving:')).toHaveTextContent('₱0.00')
    fireEvent.click(screen.getByRole('button', { name: 'Save account' }))
    expect(base.onAccountsChange.mock.calls[0][0][0]).toMatchObject({ id: 'unassigned', openingBalance: -2500 })
  })
  it('shows that a zero opening balance retains income recorded without an account', () => {
    render(<Accounts {...base} transactions={[{ id: 'old-income', type: 'income', amount: 2500, description: 'Earlier salary', date: '2026-11-01' }]} />)
    fireEvent.click(screen.getByRole('button', { name: 'Edit Unassigned account' }))
    expect(screen.getByLabelText('Opening balance (₱)')).toHaveValue(0)
    expect(screen.getByText('Balance after saving:')).toHaveTextContent('₱2,500.00')
    expect(screen.getByText(/Earlier salary/)).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Save account' }))
    expect(base.onAccountsChange.mock.calls[0][0][0].openingBalance).toBe(0)
  })
  it('allows resetting the unassigned opening balance without removing activity or the account', () => {
    render(<Accounts {...base} accounts={accounts.map(a => a.id === 'unassigned' ? { ...a, openingBalance: 2500 } : a)} />)
    fireEvent.click(screen.getByRole('button', { name: 'Edit Unassigned account' }))
    expect(screen.getByLabelText('Account name')).toBeDisabled()
    expect(screen.getByLabelText('Type')).toBeDisabled()
    expect(screen.queryByRole('button', { name: 'Archive account' })).toBeNull()
    expect(screen.queryByRole('button', { name: 'Delete account' })).toBeNull()
    fireEvent.change(screen.getByLabelText('Opening balance (₱)'), { target: { value: '0' } })
    fireEvent.click(screen.getByRole('button', { name: 'Save account' }))
    expect(base.onAccountsChange).toHaveBeenCalledWith(accounts)
    expect(base.onTransfersChange).not.toHaveBeenCalled()
  })
  it('masks a card balance without changing its amount', () => {
    render(<Accounts {...base} />)
    fireEvent.click(screen.getByRole('button', { name: 'Hide Cash balance' }))
    expect(base.onAccountsChange.mock.calls[0][0].find(a => a.id === 'cash')).toMatchObject({ balanceHidden: true, openingBalance: 100 })
  })
  it('confirms archive and preserves the stored account', () => {
    render(<Accounts {...base} />)
    fireEvent.click(screen.getByRole('button', { name: 'Edit Cash account' }))
    expect(screen.queryByRole('button', { name: 'Delete account' })).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: 'Archive account' }))
    fireEvent.click(screen.getByRole('button', { name: 'Confirm archive' }))
    expect(base.onAccountsChange.mock.calls[0][0].find(a => a.id === 'cash')).toMatchObject({ archived: true, openingBalance: 100 })
  })
  it('hides archived cards until show archived is selected', () => {
    render(<Accounts {...base} accounts={accounts.map(a => a.id === 'cash' ? { ...a, archived: true } : a)} />)
    expect(screen.queryByRole('button', { name: 'Edit Cash account' })).toBeNull()
    fireEvent.click(screen.getByLabelText('Show archived accounts'))
    expect(screen.getByRole('button', { name: 'Edit Cash account' })).toBeTruthy()
  })
  it('opens editing in a dialog and cancels without changing accounts', () => {
    render(<Accounts {...base} />)
    expect(screen.queryByRole('button', { name: '+ Add account' })).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: 'Edit Cash account' }))
    expect(screen.getByRole('dialog', { name: 'Edit account' })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Cancel' }))
    expect(screen.queryByRole('dialog')).toBeNull()
    expect(base.onAccountsChange).not.toHaveBeenCalled()
  })
  it('creates an account in the embedded workspace form and finishes', () => {
    const onDone = vi.fn()
    render(<Accounts {...base} editorOnly onDone={onDone} />)
    expect(screen.queryByRole('dialog')).toBeNull()
    fireEvent.change(screen.getByLabelText('Account name'), { target: { value: 'Wallet' } })
    fireEvent.click(screen.getByRole('button', { name: 'Save account' }))
    expect(base.onAccountsChange.mock.calls[0][0].some(a => a.name === 'Wallet')).toBe(true)
    expect(onDone).toHaveBeenCalled()
  })
  it('keeps balance validation inside the transfer modal', () => {
    render(<Accounts {...base} />)
    fireEvent.click(screen.getByRole('button', { name: 'Transfer money' }))
    expect(screen.getByRole('dialog', { name: 'Transfer money' })).toBeTruthy()
    fireEvent.keyDown(screen.getByLabelText('Transfer amount'), { key: '1' })
    expect(screen.getByRole('alert').textContent).toContain('exceeds')
    expect(screen.getByRole('button', { name: 'Record transfer' }).disabled).toBe(true)
    fireEvent.click(screen.getByRole('button', { name: 'Close Transfer money' }))
    expect(screen.queryByRole('dialog')).toBeNull()
    expect(base.onTransfersChange).not.toHaveBeenCalled()
  })
})
