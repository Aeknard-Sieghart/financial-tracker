import { beforeEach, afterEach, it, expect, vi } from 'vitest'
import { render, screen, fireEvent, cleanup } from '@testing-library/react'
import Debts from './Debts'
import { localMonth } from '../utils/bills'
const month = localMonth()
const debt = { id: 'sp', provider: 'spaylater', name: 'My SPayLater', openingPrincipal: 10000, amountType: 'variable', dueDate: `${month}-20` }
const props = { debts: [debt], transactions: [], accounts: [{ id: 'bank', name: 'Bank', openingBalance: 5000 }], transfers: [], onChange: vi.fn(), onRepay: vi.fn() }
vi.mock('./PeriodDatePicker', () => ({ default: ({ type, value, min, max, onChange }) => <input type={type === 'month' ? 'month' : 'date'} aria-label={type === 'month' ? 'Billing month' : `Choose date: ${value}`} value={value} min={min} max={max} onChange={onChange} /> }))
beforeEach(() => { HTMLDialogElement.prototype.showModal = function () { this.setAttribute('open', '') } })
afterEach(() => { cleanup(); vi.clearAllMocks() })
it('confirms archiving and restores archived debts without changing repayment history', () => {
  const entries = [{ id: 'paid', type: 'debt-payment', debtId: debt.id, debtPaymentId: 'p1', debtMonth: month, date: `${month}-01`, amount: 100 }]
  const { rerender } = render(<Debts {...props} transactions={entries} />)
  fireEvent.click(screen.getByRole('button', { name: 'Edit' }))
  expect(screen.queryByRole('button', { name: 'Delete debt' })).not.toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: 'Archive debt' }))
  expect(props.onChange).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button', { name: 'Confirm archive' }))
  const archived = props.onChange.mock.calls[0][0]
  expect(archived).toEqual([{ ...debt, archived: true }])
  expect(props.onRepay).not.toHaveBeenCalled()
  rerender(<Debts {...props} debts={archived} transactions={entries} />)
  expect(screen.queryByText(debt.name)).not.toBeInTheDocument()
  fireEvent.click(screen.getByLabelText('Show archived debts'))
  expect(screen.getByText(debt.name)).toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: 'Edit' }))
  fireEvent.click(screen.getByRole('button', { name: 'Restore debt' }))
  fireEvent.click(screen.getByRole('button', { name: 'Confirm restore' }))
  expect(props.onChange.mock.lastCall[0]).toEqual([{ ...debt, archived: false }])
})
it('deletes a debt with no repayments only after confirmation', () => {
  render(<Debts {...props} />)
  fireEvent.click(screen.getByRole('button', { name: 'Edit' }))
  fireEvent.click(screen.getByRole('button', { name: 'Delete debt' }))
  expect(props.onChange).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button', { name: 'Cancel' }))
  expect(props.onChange).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button', { name: 'Edit' }))
  fireEvent.click(screen.getByRole('button', { name: 'Delete debt' }))
  fireEvent.click(screen.getByRole('button', { name: 'Confirm delete' }))
  expect(props.onChange).toHaveBeenCalledWith([])
  expect(props.onRepay).not.toHaveBeenCalled()
})
it('rechecks linked repayments at deletion time', () => {
  const { rerender } = render(<Debts {...props} />)
  fireEvent.click(screen.getByRole('button', { name: 'Edit' }))
  fireEvent.click(screen.getByRole('button', { name: 'Delete debt' }))
  rerender(<Debts {...props} transactions={[{ id: 'fee', type: 'expense', debtId: debt.id, amount: 25 }]} />)
  fireEvent.click(screen.getByRole('button', { name: 'Confirm delete' }))
  expect(props.onChange).not.toHaveBeenCalled()
  expect(screen.getByRole('alert')).toHaveTextContent('Archive it instead')
})
it('saves a variable payment period without dividing principal into installments', () => {
  const date = new Date(`${month}-01T12:00:00`)
  const finalMonth = localMonth(new Date(date.getFullYear(), date.getMonth() + 1, 1))
  render(<Debts {...props} debts={[]} editorOnly />)
  fireEvent.change(screen.getByLabelText('Debt name'), { target: { value: 'Variable loan' } })
  for (const key of '1000000') fireEvent.keyDown(screen.getByLabelText('Opening principal owed'), { key })
  fireEvent.change(screen.getByLabelText('Amount type'), { target: { value: 'variable' } })
  fireEvent.change(screen.getByText('First monthly due date').parentElement.querySelector('input'), { target: { value: `${month}-05` } })
  fireEvent.click(screen.getByLabelText('Set final payment due date'))
  fireEvent.change(screen.getByText('Final payment due date').parentElement.querySelector('input'), { target: { value: `${finalMonth}-05` } })
  expect(screen.queryByLabelText('Total repayment (including fees)')).not.toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: 'Save debt' }))
  expect(props.onChange).toHaveBeenCalledWith([expect.objectContaining({ amountType: 'variable', openingPrincipal: 10000, dueDate: `${month}-05`, finalDueDate: `${finalMonth}-05` })])
  expect(props.onChange.mock.calls[0][0][0].monthlyAmounts).toBeUndefined()
})
it('accepts all monthly statement amounts directly in the variable debt editor', () => {
  const date = new Date(`${month}-01T12:00:00`)
  const finalMonth = localMonth(new Date(date.getFullYear(), date.getMonth() + 1, 1))
  render(<Debts {...props} debts={[]} editorOnly />)
  fireEvent.change(screen.getByLabelText('Debt name'), { target: { value: 'SPayLater' } })
  for (const key of '1000000') fireEvent.keyDown(screen.getByLabelText('Opening principal owed'), { key })
  fireEvent.change(screen.getByLabelText('Amount type'), { target: { value: 'variable' } })
  fireEvent.change(screen.getByText('First monthly due date').parentElement.querySelector('input'), { target: { value: `${month}-05` } })
  fireEvent.click(screen.getByLabelText('Set final payment due date'))
  fireEvent.change(screen.getByText('Final payment due date').parentElement.querySelector('input'), { target: { value: `${finalMonth}-05` } })
  const inputs = screen.getAllByPlaceholderText('Amount pending')
  expect(inputs).toHaveLength(2)
  for (const key of '340237') fireEvent.keyDown(inputs[0], { key })
  for (const key of '175887') fireEvent.keyDown(inputs[1], { key })
  fireEvent.click(screen.getByRole('button', { name: 'Save debt' }))
  expect(props.onChange.mock.calls[0][0][0]).toMatchObject({ openingPrincipal: 10000, monthlyAmounts: { [month]: 3402.37, [finalMonth]: 1758.87 } })
})
it('distinguishes an unknown monthly amount from an explicit zero', () => {
  render(<Debts {...props} debts={[{ ...debt, finalDueDate: debt.dueDate, monthlyAmounts: { [month]: 2200 } }]} />)
  fireEvent.click(screen.getByRole('button', { name: 'Edit' }))
  const amount = screen.getByPlaceholderText('Amount pending')
  expect(amount).toHaveValue('₱2,200.00')
  fireEvent.keyDown(amount, { key: 'Delete' })
  expect(amount).toHaveValue('')
  fireEvent.keyDown(amount, { key: '0' })
  expect(amount).toHaveValue('₱0.00')
  fireEvent.click(screen.getByRole('button', { name: 'Save debt' }))
  expect(props.onChange.mock.calls[0][0][0].monthlyAmounts[month]).toBe(0)
})
it('calculates fixed payments from the total and selected payment period', () => {
  const date = new Date(`${month}-01T12:00:00`)
  const finalMonth = localMonth(new Date(date.getFullYear(), date.getMonth() + 1, 1))
  render(<Debts {...props} debts={[]} editorOnly />)
  fireEvent.change(screen.getByLabelText('Debt name'), { target: { value: 'Fixed loan' } })
  for (const key of '1000000') fireEvent.keyDown(screen.getByLabelText('Opening principal owed'), { key })
  fireEvent.change(screen.getByText('First monthly due date').parentElement.querySelector('input'), { target: { value: `${month}-05` } })
  fireEvent.change(screen.getByLabelText('Monthly payment setup'), { target: { value: 'calculated' } })
  fireEvent.change(screen.getByText('Final payment due date').parentElement.querySelector('input'), { target: { value: `${finalMonth}-05` } })
  expect(screen.getByRole('status')).toHaveTextContent('2 monthly payments')
  expect(screen.getByRole('status')).toHaveTextContent('₱5,000.00')
  fireEvent.click(screen.getByRole('button', { name: 'Save debt' }))
  expect(props.onChange).toHaveBeenCalledWith([expect.objectContaining({ amountType: 'fixed', paymentMode: 'calculated', totalRepayment: 10000, paymentAmount: 5000, finalDueDate: `${finalMonth}-05` })])
})
it('keeps unpaid debt visible after the schedule ends without offering new statement months', () => {
  render(<Debts {...props} debts={[{ ...debt, dueDate: '2025-12-05', finalDueDate: '2026-01-05', monthlyAmounts: { '2025-12': 5000, '2026-01': 5000 } }]} />)
  expect(screen.getByText('Schedule ended')).toBeInTheDocument()
  expect(screen.getByText('₱10,000.00 principal remaining')).toBeInTheDocument()
  expect(screen.queryByRole('button', { name: 'Set amount' })).not.toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: 'View final month' }))
  expect(screen.getByLabelText('Billing month')).toHaveValue('2026-01')
  expect(screen.getByRole('button', { name: 'Edit month amount' })).toBeInTheDocument()
})
it('saves a statement amount without modifying outstanding principal', () => {
  render(<Debts {...props} />)
  expect(screen.getAllByText('Amount pending').length).toBeGreaterThan(0)
  expect(screen.queryByRole('button', { name: 'Repay' })).toBeNull()
  fireEvent.click(screen.getByRole('button', { name: 'Set amount' }))
  for (const key of '220000') fireEvent.keyDown(screen.getByLabelText('Monthly amount due'), { key })
  fireEvent.click(screen.getByRole('button', { name: 'Save amount' }))
  expect(props.onChange.mock.calls[0][0][0]).toMatchObject({ openingPrincipal: 10000, monthlyAmounts: { [month]: 2200 } })
})
