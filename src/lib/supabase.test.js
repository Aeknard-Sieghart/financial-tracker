import { afterEach, expect, it, vi } from 'vitest'
vi.mock('@supabase/supabase-js', () => ({ createClient: vi.fn((url, key, options) => ({ url, key, options })) }))
afterEach(() => { vi.unstubAllEnvs(); vi.unstubAllGlobals(); vi.resetModules() })
it('binds data requests to a captured user token and aborts them when the workspace closes', async () => {
  vi.stubEnv('VITE_SUPABASE_URL', 'https://test.supabase.co')
  vi.stubEnv('VITE_SUPABASE_PUBLISHABLE_KEY', 'sb_publishable_test')
  const { createWorkspaceClient } = await import('./supabase')
  const { createWorkspaceLifetime } = await import('../utils/workspaceStorage')
  const a = createWorkspaceLifetime(), b = createWorkspaceLifetime()
  const clientA = createWorkspaceClient({ access_token: 'token-a' }, a)
  const clientB = createWorkspaceClient({ access_token: 'token-b' }, b)
  expect(await clientA.options.accessToken()).toBe('token-a')
  expect(await clientB.options.accessToken()).toBe('token-b')
  const request = vi.fn(async () => new Response('[]'))
  vi.stubGlobal('fetch', request)
  await clientA.options.global.fetch('https://test.supabase.co/rest/v1/tracker_snapshots')
  const signal = request.mock.calls[0][1].signal
  expect(signal.aborted).toBe(false)
  a.abort()
  expect(signal.aborted).toBe(true)
  await expect(clientA.options.accessToken()).rejects.toThrow('Workspace closed')
  expect(await clientB.options.accessToken()).toBe('token-b')
  expect(b.signal.aborted).toBe(false)
})
